/// Widget de ícone colorido padrão da aplicação
class HabittusIcon extends StatelessWidget {
  final IconData icon;
  final Color? color;
  final double size;
  final Color? backgroundColor;
  final double? backgroundSize;
  final double? borderRadius;

  const HabittusIcon({
    super.key,
    required this.icon,
    this.color,
    this.size = 24,
    this.backgroundColor,
    this.backgroundSize,
    this.borderRadius,
  });

  @override
  Widget build(BuildContext context) {
    final iconWidget = Icon(
      icon,
      color: color ?? HabittusIcons.primaryColor,
      size: size,
    );

    if (backgroundColor != null) {
      return Container(
        width: backgroundSize ?? size + 16,
        height: backgroundSize ?? size + 16,
        decoration: BoxDecoration(
          color: backgroundColor,
          borderRadius: BorderRadius.circular(borderRadius ?? 12),
        ),
        child: Center(child: iconWidget),
      );
    }

    return iconWidget;
  }
}

/// Widget de ícone circular com fundo
class HabittusCircleIcon extends StatelessWidget {
  final IconData icon;
  final Color? iconColor;
  final Color? backgroundColor;
  final double size;
  final double iconSize;
  final VoidCallback? onTap;

  const HabittusCircleIcon({
    super.key,
    required this.icon,
    this.iconColor,
    this.backgroundColor,
    this.size = 48,
    this.iconSize = 24,
    this.onTap,
  });

  @override
  Widget build(BuildContext context) {
    final widget = Container(
      width: size,
      height: size,
      decoration: BoxDecoration(
        color: backgroundColor ?? const Color(0xFFE4EAD8),
        shape: BoxShape.circle,
      ),
      child: Center(
        child: Icon(
          icon,
          color: iconColor ?? HabittusIcons.primaryColor,
          size: iconSize,
        ),
      ),
    );

    if (onTap != null) {
      return InkWell(
        onTap: onTap,
        borderRadius: BorderRadius.circular(size / 2),
        child: widget,
      );
    }

    return widget;
  }
}

/// Widget de ícone com label
class HabittusIconLabel extends StatelessWidget {
  final IconData icon;
  final String label;
  final Color? iconColor;
  final Color? backgroundColor;
  final bool selected;
  final VoidCallback? onTap;

  const HabittusIconLabel({
    super.key,
    required this.icon,
    required this.label,
    this.iconColor,
    this.backgroundColor,
    this.selected = false,
    this.onTap,
  });

  @override
  Widget build(BuildContext context) {
    return InkWell(
      onTap: onTap,
      borderRadius: BorderRadius.circular(16),
      child: AnimatedContainer(
        duration: const Duration(milliseconds: 200),
        padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 10),
        decoration: BoxDecoration(
          color: selected 
              ? const Color(0xFFE4EAD8) 
              : backgroundColor ?? const Color(0xFFF6F8F0),
          borderRadius: BorderRadius.circular(16),
          border: Border.all(
            color: selected 
                ? HabittusIcons.primaryColor 
                : const Color(0xFFD9E1D0),
            width: 2,
          ),
        ),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            HabittusCircleIcon(
              icon: icon,
              iconColor: iconColor ?? HabittusIcons.primaryColor,
              size: 40,
              iconSize: 20,
            ),
            const SizedBox(height: 6),
            Text(
              label,
              style: TextStyle(
                fontSize: 11,
                fontWeight: selected ? FontWeight.w600 : FontWeight.normal,
                color: selected ? HabittusIcons.primaryColor : Colors.black87,
              ),
              textAlign: TextAlign.center,
              maxLines: 2,
              overflow: TextOverflow.ellipsis,
            ),
          ],
        ),
      ),
    );
  }
}
